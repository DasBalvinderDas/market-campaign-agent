#!/usr/bin/env python3
"""Write docs/FLOW_PREVIEW.md: the conversation turn by turn, with the exact text the tools return.

No cloud access needed (it uses the in-memory copy of the demo data). The assistant adds at most a friendly sentence of its
own around this text. Run it to see the flow after a change:  python scripts/preview_flow.py
"""
import os
import sys
from datetime import date, timedelta
from pathlib import Path

os.environ["DATA_BACKEND"] = "memory"
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from launchkit_provisioner import decision_flow, execution  # noqa: E402
from launchkit_provisioner.repositories import set_repo  # noqa: E402
from launchkit_provisioner.repositories.memory_repo import MemoryRepository  # noqa: E402
from launchkit_provisioner.tools import brief_tools as bt  # noqa: E402
from launchkit_provisioner.tools import orchestration_tools as ot  # noqa: E402
from launchkit_provisioner.tools import sourcing_tools as st  # noqa: E402


class _Executor:
    """Stands in for Application Integration: answers like the workflows do."""
    def execute(self, trigger, inputs):
        return {"po_number": f"PO-{inputs.get('plan_line_id')}", "transfer_number": f"TR-{inputs.get('plan_line_id')}", "execution_id": "x"}

    def start(self, trigger, inputs):
        return {"executionId": "demo-approval", "executionFailed": False}


def fresh():
    repo = MemoryRepository()
    repo.t["approvers"] = [{"approver_role": r, "email": e, "active": True} for r, e in
                           (("VP Product Marketing", "vp@example.com"), ("CMO", "cmo@example.com"), ("Launch Team", "team@example.com"))]
    set_repo(repo)
    return repo


def turn(out, user, shows, note=""):
    out.append(f"### 🧑 You: `{user}`\n")
    if note:
        out.append(f"*{note}*\n")
    out.append("**🤖 The assistant shows:**\n")
    out.append("\n".join("> " + ln if ln.strip() else ">" for ln in shows.splitlines()) + "\n")


def main():
    d = date.today() + timedelta(days=25)
    iso, say = d.isoformat(), f"{d.day} {d:%B}"
    out = ["# Flow preview: what the assistant shows at each step\n",
           f"Generated by `python scripts/preview_flow.py` from the real tools, for a date 25 days from today (**{say}**). Dollar amounts match the demo data.\n"
           "The assistant adds at most a friendly sentence of its own around each block; the tables, numbers and questions are exactly this text.\n",
           "Contents: **A.** Hello · **B.** A campaign for 300 people · **C.** One item, inside the limit · **D.** One item, above the limit\n"]

    # ---------------------------------------------------------------- A
    fresh()
    out.append("---\n## A. Hello\n")
    turn(out, "Hi", ot.show_capabilities()["display_markdown"])

    # ---------------------------------------------------------------- B
    repo = fresh()
    out.append("---\n## B. A campaign for 300 people (the main story)\n")
    msg = f"Hi, I am looking for a campaign for 300 people on {say}."
    r = ot.show_checklist("campaign", "", 300, say)
    turn(out, msg, r["display_markdown"], "It read the people and the date from the sentence, so it asks only what is missing: where.")
    r = ot.show_checklist("campaign", "", 300, say, "USA")
    turn(out, "USA", r["display_markdown"], "The place is known. Next: a name, with ideas to pick from.")
    name = r["name_suggestions"][1]
    created = bt.create_campaign(name, iso, 300, "USA")
    r = ot.show_checklist("campaign", name, 300, say, "USA")
    turn(out, "2", created["display_markdown"] + "\n\n" + r["display_markdown"],
         "The campaign is created the moment it is named; the same message goes on to our offer.")
    sug = r["suggested"]
    rid = bt.register_launch_request(name, "300 people", iso)["request_id"]
    built = bt.build_requirements(rid, [bt.BundleRequest(**b) for b in sug["bundles"]], [bt.ItemRequest(**i) for i in sug["items"]])
    turn(out, "Use the suggested plan", built["bom_markdown"] + "\n\n" + built["advice_markdown"],
         "The shopping list, and the advice. It waits for you.")
    plan = st.build_scenarios(rid)
    turn(out, "Looks good", "\n\n".join([plan["tldr"], plan["stock_report"], plan["vendor_report"], plan["decision_card"], plan["date_options"]]),
         "The plan: in short, stock, vendors, three choices and other dates. It waits for your choice.")
    ex = _Executor()
    res = decision_flow.authorize(repo, ex, rid, "2", "Cheapest choice with spare time")
    turn(out, "Choose option 2", "**" + res["announce"] + "**\n\n" + res["display_markdown"],
         "Above $5,000, so an approval email goes out first. Nothing is bought yet.")
    dec = repo.get_decision_for_request(rid)
    repo.decide(dec["decision_id"], "APPROVED", "Application Integration approval", "ok")
    done = execution.execute_plan(repo, ex, rid)
    turn(out, "What is the status of that request?", done["display_markdown"],
         "After the approver clicked Approve in the email: the orders are placed, with the story behind them.")

    # ---------------------------------------------------------------- C
    repo = fresh()
    out.append("---\n## C. One item, inside the limit (ordered at once)\n")
    msg = f"Hi, I need 30 name badges with lanyards for the USA by {say}."
    r = ot.show_checklist("items", "", 0, say, "USA")
    rid = bt.register_launch_request("Quick purchase", "30 name badges", iso)["request_id"]
    built = bt.build_requirements(rid, items=[bt.ItemRequest(item="name badge", quantity=30, region=r["region"])])
    turn(out, msg, built["bom_markdown"] + "\n\n" + built["advice_markdown"],
         "It read the item, the place and the date from the sentence: no more questions, straight to the list.")
    plan = st.build_scenarios(rid)
    res = decision_flow.authorize(repo, _Executor(), rid, "recommended", "Best choice within the automatic limit")
    done = execution.execute_plan(repo, _Executor(), rid)
    turn(out, "Looks good", done["display_markdown"],
         f"$67.50 is under $5,000, so it is approved automatically ({plan['decision_mode']}). No choices table and no email: "
         "the assistant orders in the same turn and shows this summary.")

    # ---------------------------------------------------------------- D
    repo = fresh()
    out.append("---\n## D. One item, above the limit (approval, then order)\n")
    msg = f"Hi, I need 6 venue display stands in the USA by {say}."
    rid = bt.register_launch_request("Quick purchase", "6 stands", iso)["request_id"]
    built = bt.build_requirements(rid, items=[bt.ItemRequest(item="venue display stand", quantity=6, region="US")])
    turn(out, msg, built["bom_markdown"] + "\n\n" + built["advice_markdown"])
    plan = st.build_scenarios(rid)
    turn(out, "Looks good", "\n\n".join([plan["tldr"], plan["decision_card"], plan["date_options"]]),
         "Note the dates table: a week later is cheaper (DisplayCo's early-bird price).")
    ex = _Executor()
    res = decision_flow.authorize(repo, ex, rid, "1", "Cheapest")
    turn(out, "Choose option 1", "**" + res["announce"] + "**\n\n" + res["display_markdown"])
    dec = repo.get_decision_for_request(rid)
    repo.decide(dec["decision_id"], "REJECTED", "Application Integration approval", "no")
    turn(out, "What is the status of that request?  (the approver clicked Reject)",
         decision_flow.status(repo, rid, executor=ex)["display_markdown"] + "\n\nNothing was bought.")
    path = Path(__file__).resolve().parent.parent / "docs" / "FLOW_PREVIEW.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path} ({len(out)} blocks)")


if __name__ == "__main__":
    main()
